// Reflect language on <html> for CSS targeting (script-aware fonts, etc.)
const applyHtmlLang = (lng: string) => {
  if (typeof document === "undefined") return;
  const def = getLanguageDef(lng);
  document.documentElement.lang = def.code;
  document.documentElement.dataset.lang = def.code;
};
applyHtmlLang(i18n.language || DEFAULT_LANGUAGE);
